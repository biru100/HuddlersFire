def trim_ink(tile):
    # Keep the outside pixel and solid dark materials. Lift only dark ink just
    # inside the silhouette toward the colour of its immediate lit neighbour.
    alpha = tile.getchannel('A')
    padded = ImageOps.expand(alpha, border=4, fill=0)
    def inside(radius):
        inner = padded.filter(ImageFilter.MinFilter(2*radius+1))
        return np.asarray(inner.crop((4,4,4+tile.width,4+tile.height))) > 0
    color = np.asarray(tile.convert('RGB'),dtype=np.float32)
    # Transparent RGB must not contribute a fringe, even on the crop boundary.
    covered = Image.composite(tile.convert('RGB'),Image.new('RGB',tile.size),alpha)
    light = np.asarray(covered.filter(ImageFilter.MaxFilter(5)),dtype=np.float32)
    delta = np.maximum(light-color,0)
    weight = (inside(1) & ~inside(4)) * np.clip((delta.mean(axis=2)-10)/65,0,.52)
    result = Image.fromarray(np.uint8(color+delta*weight[...,None]))
    result.putalpha(alpha)
    return result


