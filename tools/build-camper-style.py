ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / 'art/sprites/camper-style-release'
PUBLIC = ROOT / 'web/public/sprites'
REGISTRY = ROOT / 'web/lib/camp-style-files.mjs'
files, frames = {}, {}
previous_files = json.loads(REGISTRY.read_text(encoding='utf-8').split('export const STYLE_FILES = ')[1].split(';')[0])
parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument('--landscapes-only', action='store_true')
options = parser.parse_args()
sources = json.loads((SOURCE/'sources.json').read_text())['originals']
art = {}
for name, receipt in sources.items():
    if options.landscapes_only and name not in ('scenery.png','ground.png','field.png'):
        continue
    raw = (SOURCE/name).read_bytes()
    if sha256(raw).hexdigest() != receipt['sha256']:
        raise ValueError(f'Original differs from recorded art: {name}')
    art[Path(name).stem] = Image.open(BytesIO(raw)).convert('RGBA')


def crop(sheet, box, size):
    tile = art[sheet].crop(box).resize(size, Image.Resampling.LANCZOS)
    tile.putalpha(tile.getchannel('A').point(lambda v: 255 if v >= 120 else 0))
    return tile


def save(key, image, *, landscape=False):
    # Pillow/zlib versions can encode identical pixels differently. Retain the
    # registered immutable file when rebuilding leaves its decoded pixels intact.
    entry = previous_files.get(key)
    lossless_webp = key in ('camp-scenery', 'camp-scenery-dark')
    suffix = 'webp' if landscape or lossless_webp else 'png'
    if entry and entry['url'].endswith('.' + suffix):
        path = PUBLIC / Path(entry['url']).name
        if path.is_file() and sha256(path.read_bytes()).hexdigest() == entry['sha256']:
            with Image.open(path) as previous:
                if previous.size == image.size and previous.convert('RGBA').tobytes() == image.convert('RGBA').tobytes():
                    files[key] = entry
                    return
    buf = BytesIO()
    if landscape:
        # The near floor carries small leaf and grout marks even under the camper's feet.
        image.save(buf, format='WEBP', quality=92 if key.startswith('landscape-') else 82, method=6)
    elif lossless_webp:
        image.save(buf, format='WEBP', lossless=True, exact=True, method=6)
    else:
        image.save(buf, format='PNG', optimize=True)
    raw = buf.getvalue()
    digest = sha256(raw).hexdigest()
    name = f'camper-style-{key}.{digest[:12]}.{suffix}'
    output = PUBLIC/name
    if not output.is_file() or output.read_bytes()!=raw:
        output.write_bytes(raw)
    files[key] = dict(url='/sprites/'+name, width=image.width, height=image.height,
                      bytes=len(raw), sha256=digest, sampling='nearest')


def write_module(frame_json):
    module = '// Generated by tools/build-camper-style.py.\n'
    module += 'export const STYLE_FILES = '+json.dumps(files,separators=(',',':'),indent=2)+';\n'
    module += 'export const STYLE_FRAMES = '+frame_json
    REGISTRY.write_text(module,encoding='utf-8',newline='\n')


