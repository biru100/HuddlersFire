rows, x, y, row_height = [], 2, 2, 0
for sheet,name,box,reference,foot in props:
    w = widths[name.split('-')[0]]
    h = round(w*reference[1]/reference[0])
    if x+w+2 > 640:
        x,y,row_height = 2,y+row_height+4,0
    rows.append((sheet,name,box,reference,foot,x,y,w,h))
    row_height = max(row_height,h)
    x += w+4
scenery = Image.new('RGBA',(640,y+row_height+2))
for sheet,name,box,reference,foot,x,y,w,h in rows:
    tile = booth((w,h)) if name=='gameBooth' else crop(sheet,box,(w,h))
    if w>40:
        tile = trim_ink(tile)
    # Keep faces and official posters the sharpest accents at follow-camera size.
    if sheet=='scenery':
        tile=ImageEnhance.Color(tile).enhance(.93)
    if name=='fence':
        tile = ImageOps.mirror(tile)
    profile = scenery_profile(name)
    if name.startswith('fence-'):
        tile = joined_fence(tile,profile)
        foot = [v/n for v,n in zip(profile['origin'],reference)]
    tile = camp_material_colors(refine_material(tile,name),name)
    # Reserve a palette for small props so petals and lantern glass keep their accents.
    alpha = tile.getchannel('A')
    tile = tile.convert('RGB').quantize(colors=120,dither=Image.Dither.NONE).convert('RGBA')
    tile.putalpha(alpha)
    scenery.paste(tile,(x,y))
    placement = dict(width=w)
    if profile:
        placement['profile'] = profile
    frames[name] = dict(sheet='camp-scenery',x=x,y=y,w=w,h=h,referenceSize=reference,placement=placement,sampling='nearest',
                        contacts={'ground':{'x':round(w*foot[0]),'y':round(h*foot[1])}})
