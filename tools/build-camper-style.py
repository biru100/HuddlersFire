def surfaces(key, color, relief=True, graded=False):
    mask = color.getchannel('A')
    layer = color if graded else color.convert('RGB').quantize(colors=150, dither=Image.Dither.NONE).convert('RGBA')
    layer.putalpha(mask)
    save(key, layer)
    mono = ImageOps.grayscale(layer).quantize(colors=48).convert('RGBA')
    mono.putalpha(mask)
    save(key+'-dark', mono)
    if relief:
        # Use broad form and bevel neighbouring the silhouette. Individual
        # grain marks and bright highlights belong to the painted colour only.
        # Divide blurred premultiplied luminance by coverage near cutout edges.
        import numpy as np
        coverage = np.asarray(mask.filter(ImageFilter.GaussianBlur(2)), dtype=float)
        luminance = ImageOps.grayscale(layer)
        covered = Image.composite(luminance, Image.new('L',layer.size), mask)
        broad = np.asarray(covered.filter(ImageFilter.GaussianBlur(2)), dtype=float)
        luma = Image.fromarray(np.uint8(np.clip(broad*255/np.maximum(coverage,1),0,255))).load()
        silhouette = mask.filter(ImageFilter.GaussianBlur(4)).load()
        normal = Image.new('RGBA', layer.size)
        pixels = normal.load()
        alpha = mask.load()
        for y in range(layer.height):
            for x in range(layer.width):
                if not alpha[x,y]:
                    continue
                center = luma[x,y]
                def sample(dx,dy):
                    u,v = x+dx,y+dy
                    return luma[u,v] if 0<=u<layer.width and 0<=v<layer.height and alpha[u,v] else center
                # The occupied side of an edge slopes away from the viewer.
                du = (sample(-2,0)-sample(2,0))*.30
                dv = (sample(0,2)-sample(0,-2))*.30
                du += (silhouette[max(0,x-2),y]-silhouette[min(layer.width-1,x+2),y])*.53
                dv += (silhouette[x,min(layer.height-1,y+2)]-silhouette[x,max(0,y-2)])*.53
                nx,ny=int(du),int(dv)+22
                nz=round(max(1,126**2-nx**2-ny**2)**.5)
                pixels[x,y] = (128+nx,128+ny,128+nz,255)
        save('normal-'+key, normal)


# A booth's screen tracks the exhibition-cover aspect while timber and awning keep their proportions.
def booth(size):
    image = art['scenery'].crop((47,877,396,1183))
    result = Image.new('RGBA',size)
    xs,ys = [0,58,278,349],[0,152,226,306]
    dx = [round(x*size[0]/118) for x in (0,16,102,118)]
    dy = [round(y*size[1]/96) for y in (0,33,73,96)]
    for j in range(3):
        for i in range(3):
            part = image.crop((xs[i],ys[j],xs[i+1],ys[j+1]))
            result.paste(part.resize((dx[i+1]-dx[i],dy[j+1]-dy[j]),Image.Resampling.LANCZOS),(dx[i],dy[j]))
    result.putalpha(result.getchannel('A').point(lambda v: 255 if v>=120 else 0))
    return result


