// Build the nine scenery sprites, their monochrome companions and matching relief atlas.
import {createHash} from 'node:crypto';
import {readFile, writeFile} from 'node:fs/promises';
import {createCanvas, loadImage} from '@napi-rs/canvas';
import sharp from 'sharp';
import {SPRITE_MANIFEST} from '../lib/camp-sprite-manifest.mjs';

const root = new URL('../../', import.meta.url);
const source = await loadImage(await readFile(new URL('art/sprites/landscape-release/scenery-source.png', root)));
const rows = [
  [
    {id:'tree', crop:[16,27,388,377], w:110, h:107, foot:[55,103]},
    {id:'tree-birch', crop:[438,27,383,374], w:106, h:104, foot:[50,100]},
    {id:'tree-pine', crop:[895,16,313,388], w:92, h:114, foot:[44,110]},
  ],
  [
    {id:'tent', crop:[14,498,398,289], w:118, h:86, foot:[58,80]},
    {id:'shade', crop:[440,463,370,332], w:102, h:92, foot:[50,80]},
    {id:'trampoline', crop:[863,543,362,237], w:80, h:52, foot:[40,47]},
  ],
  [
    {id:'gameBooth', crop:[20,870,384,365], w:116, h:101, foot:[58,97]},
    {id:'crate', crop:[495,923,266,266], w:44, h:44, foot:[23,40]},
    {id:'fence', crop:[857,918,370,299], w:62, h:50, foot:[30,38]},
  ],
];
const gap = 2;
const width = Math.max(...rows.map(row => row.reduce((sum, f) => sum + f.w + gap, gap)));
const height = rows.reduce((sum, row) => sum + Math.max(...row.map(f => f.h)) + gap, gap);
const clamp = (value, min, max) => Math.min(max, Math.max(min, value));
const atlases = [
  {id:'camp-scenery', colours:128},
  {id:'camp-scenery-dark', colours:48},
  {id:'normal-camp-scenery', colours:10},
].map(spec => ({...spec, canvas:createCanvas(width, height)}));

// Preserve the illustrated roof scallops and posts while fitting the real, live game cover.
// Only the empty poster well grows. Its mounting frame stays visible around every cover.
function fitBooth(context, left, top) {
  const xs = [0,87,296,384], ys = [0,148,230,365];
  const dx = [0,21,95,116], dy = [0,32,72,101];
  for (let y=0; y<3; y++) for (let x=0; x<3; x++) {
    context.drawImage(source,
      left+xs[x], top+ys[y], xs[x+1]-xs[x], ys[y+1]-ys[y],
      dx[x], dy[y], dx[x+1]-dx[x], dy[y+1]-dy[y]);
  }
}
const frames = {};
let top = gap;
for (const row of rows) {
  let left = gap;
  for (const {id, crop, w, h, foot} of row) {
    const c = createCanvas(w,h).getContext('2d');
    c.imageSmoothingQuality = 'high';
    // propDisplay flips the opposite run of the playground's L-shaped fence.
    if (id==='fence') {c.translate(w,0);c.scale(-1,1);}
    if (id==='gameBooth') fitBooth(c,crop[0],crop[1]);
    else c.drawImage(source,...crop,0,0,w,h);
    const data = c.getImageData(0,0,w,h).data;
    const [color,dark,normal] = atlases.map(() => c.createImageData(w,h));
    const luma = (x,y,fallback) => {
      const i = (clamp(y,0,h-1)*w+clamp(x,0,w-1))*4;
      return data[i+3]<120 ? fallback : .30*data[i]+.59*data[i+1]+.11*data[i+2];
    };
    for (let y=0; y<h; y++) for (let x=0; x<w; x++) {
      const i = (y*w+x)*4;
      // Eliminate sub-pixel matte noise. Colour, normal and dynamic shadow share this mask.
      if (data[i+3]<120) continue;
      color.data.set([data[i],data[i+1],data[i+2],255],i);
      const center = luma(x,y,0);
      const value = Math.round(center/5)*5;
      dark.data.set([value,value,value,255],i);
      // Keep the broad normal neutral. Only a substantial edge in the drawing catches light.
      const slope = (a,b) => Math.abs(a-b)>=30 ? Math.sign(a-b)*24 : 0;
      normal.data.set([128+slope(luma(x-1,y,center),luma(x+1,y,center)),
        148+slope(luma(x,y+1,center),luma(x,y-1,center)),246,255],i);
    }
    [color,dark,normal].forEach((frame,i) => atlases[i].canvas.getContext('2d').putImageData(frame,left,top));
    const {displayWidth,depth,direction} = SPRITE_MANIFEST.sprites[id];
    frames[id] = {sheet:'camp-scenery', x:left, y:top, w, h, displayWidth,depth,direction,
      contacts:{ground:{x:foot[0],y:foot[1]}}, sampling:'nearest'};
    if (id==='gameBooth') frames[id].poster = {x:22/w,y:33/h,w:72/w,h:38/h};
    left += w+gap;
  }
  top += Math.max(...row.map(f => f.h))+gap;
}
const files = {};
for (const {id, canvas, colours} of atlases) {
  const png = await sharp(canvas.toBuffer('image/png')).png({palette:true,colours,dither:0,effort:9}).toBuffer();
  const sha256 = createHash('sha256').update(png).digest('hex');
  const filename = id+'.'+sha256.slice(0,12)+'.png';
  await writeFile(new URL('web/public/sprites/'+filename,root),png);
  files[id] = {url:'/sprites/'+filename,width,height,bytes:png.length,sha256,sampling:'nearest'};
}
await writeFile(new URL('web/lib/camp-scenery-files.mjs',root),
  '// Generated by web/scripts/build-camp-scenery.mjs.\n'+
  'export const SCENERY_FILES = '+JSON.stringify(files,null,2)+';\n'+
  'export const SCENERY_FRAMES = '+JSON.stringify(frames,null,2)+';\n');
console.log(Object.values(files).map(f => f.url+' ('+f.bytes+' B)').join('\n'));
