// Rebuild the three map atlases from the four retained image-generation originals.
import {createHash} from 'node:crypto';
import {readFileSync, writeFileSync} from 'node:fs';
import {join} from 'node:path';
import {fileURLToPath} from 'node:url';
import {createCanvas} from '@napi-rs/canvas';
import sharp from 'sharp';
import {getMap} from '../lib/camp-maps.mjs';

const root = fileURLToPath(new URL('../../', import.meta.url));
const sources = join(root,'art/sprites/landscape-release');
const size = 248, skyHeight = 83;
const files = {}, originals = {};
const hash = data => createHash('sha256').update(data).digest('hex');
const mix = (a,b,t) => a + (b-a)*t;
const luminance = (r,g,b) => .30*r + .58*g + .12*b;
const clamp = value => Math.min(255,Math.max(0,Math.round(value)));

async function resizeSource(name,w,h) {
  const png = readFileSync(join(sources,name+'.png'));
  const {width,height} = await sharp(png).metadata();
  originals[name] = {file:name+'.png',width,height,bytes:png.length,sha256:hash(png)};
  return sharp(png).removeAlpha().resize(w,h,{fit:'fill'}).raw().toBuffer();
}

// Paint an anti-aliased wear mask in world coordinates following the actual portals.
function routeMask(mapId) {
  const c = createCanvas(size,size).getContext('2d');
  const map = getMap(mapId), extent = 2*map.bounds.edge;
  c.translate(size/2,size/2);
  c.scale(size/extent,size/extent);
  c.strokeStyle = 'white';
  c.lineCap = c.lineJoin = 'round';
  for (const {points,width} of map.routes) {
    c.beginPath();
    c.moveTo(...points[0]);
    for (let i=1;i<points.length-1;i++) {
      const [x,y] = points[i], [nx,ny] = points[i+1];
      c.quadraticCurveTo(x,y,(x+nx)/2,(y+ny)/2);
    }
    c.lineTo(...points.at(-1));
    for (const [growth,alpha] of [[1.30,.13],[1,.22],[.70,.32],[.40,.24]]) {
      c.globalAlpha=alpha;
      c.lineWidth=width/40*growth;
      c.stroke();
    }
  }
  return c.getImageData(0,0,size,size).data;
}

function gradeGround(mapId,r,g,b,wear) {
  const tone=luminance(r,g,b);
  if (mapId==='camp') {
    // Lift the midtones of the indirect albedo before the night shader is applied.
    const lifted=[30+.90*r,27+.91*g,24+.91*b];
    const trail=[tone*.87+87,tone*.81+55,tone*.62+35];
    return lifted.map((v,i)=>mix(v,trail[i],wear*.80));
  }
  if (mapId==='playground') {
    const lawn=[.83*r+.08*tone+12,.75*g+.14*tone+17,.72*b+.17*tone+19];
    return lawn.map((v,i)=>mix(v,[tone+56,tone+24,tone-16][i],wear*.90));
  }
  // Lightly polished stone at the approaches to the two exhibit booths.
  return [r,g,b].map((v,i)=>mix(v,tone,.15)+wear*[9,10,12][i]);
}

function gradeSky(mapId,r,g,b) {
  const tone=luminance(r,g,b);
  if (mapId==='camp') return [7+tone*.115,15+tone*.14,25+tone*.19];
  if (mapId==='showroom') return [r*.56+71,g*.56+65,b*.53+57];
  return [r*.61+57,g*.63+62,b*.57+60];
}

// Quantize the distant sky separately so the dark ridgelines retain their own palette.
async function indexStrip(pixels,height) {
  const strip=await sharp(pixels,{raw:{width:size,height,channels:3}})
    .png({palette:true,colors:16,dither:0,effort:10}).toBuffer();
  return sharp(strip).raw().toBuffer();
}

const sky=await resizeSource('distant',size,skyHeight);
for (const mapId of ['camp','playground','showroom']) {
  const floor=await resizeSource(mapId,size,size);
  const wear=routeMask(mapId);
  const pixels=Buffer.alloc(size*(size+skyHeight)*3);
  for(let i=0;i<floor.length;i+=3) {
    const grain=.78+.22*((floor[i]+2*floor[i+1]+floor[i+2])%17)/16;
    const value=gradeGround(mapId,floor[i],floor[i+1],floor[i+2],wear[i/3*4+3]/255*grain);
    pixels.set(value.map(clamp),i);
  }
  for(let i=0;i<sky.length;i+=3) {
    pixels.set(gradeSky(mapId,sky[i],sky[i+1],sky[i+2]).map(clamp),floor.length+i);
  }
  const height=size+skyHeight;
  const strips=await Promise.all([indexStrip(pixels.subarray(0,floor.length),size),indexStrip(pixels.subarray(floor.length),skyHeight)]);
  const png=await sharp(Buffer.concat(strips),{raw:{width:size,height,channels:3}})
    .png({palette:true,colors:256,dither:0,compressionLevel:9,effort:10}).toBuffer();
  const id='landscape-'+mapId, sha256=hash(png), name=id+'.'+sha256.slice(0,12)+'.png';
  writeFileSync(join(root,'web/public/sprites',name),png);
  files[id]={url:'/sprites/'+name,width:size,height,bytes:png.length,sha256,sampling:'nearest'};
}
writeFileSync(join(root,'web/lib/camp-landscape-files.mjs'),'// Generated by web/scripts/build-landscape-art.mjs.\nexport const LANDSCAPE_FILES = '+JSON.stringify(files,null,2)+';\n');
writeFileSync(join(sources,'sources.json'),JSON.stringify({generator:'ImageGen',briefs:'briefs.json',originals},null,2)+'\n');
console.log(Object.values(files).map(f=>f.url+' '+f.bytes).join('\n'));
