export function splitAtCollar(source,width,height,key,style,direction){
  const edge=poseCollars[key]?.[style][direction];
  if(!edge)return null;
  const body=new Uint8ClampedArray(source.length),head=new Uint8ClampedArray(source.length);
  const hands=poseHands[key]?.[style][direction]??[];
  let stop=1;
  for(let x=0;x<width;x++){
    while(x>xStops[stop])stop++;
    const progress=(x-xStops[stop-1])/(xStops[stop]-xStops[stop-1]);
    const cut=Math.round(edge[stop-1]+progress*(edge[stop]-edge[stop-1]));
    const palm=hands.find(([left,,right])=>x>=left-1&&x<=right+1);
    const cuff=palm?Math.min(cut,palm[1]-1):cut;
    for(let y=0;y<height;y++){
      const i=(y*width+x)*4;
      const layer=y<cuff?head:body;
      layer.set(source.subarray(i,i+4),i);
    }
  }
  return {body,head};
}
